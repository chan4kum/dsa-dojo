"""Builds notes/*.md from _src/*.md.

Placeholders in the sources:
  {{ladder}}            table of this topic's practice problems (from problems/<topic>.py)
  {{solution:topic/N}}  tested reference solution of problem N, as a code block
  {{trace:name}}        hand-trace table generated by tools/traces.py

    python tools/build_notes.py
"""

import re
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tools"))
import anchors  # noqa: E402
import coverage  # noqa: E402
from traces import TRACES  # noqa: E402

from dsa import DIFF, TOPICS, by_difficulty, load  # noqa: E402


def ladder(topic):
    """Markdown table of a topic's problems, easiest first, each linked to LeetCode."""
    rows = ["| id | difficulty | problem | LeetCode | pattern it trains |", "|---|---|---|---|---|"]
    for n, p in by_difficulty(load(topic)):
        rows.append(
            f"| `{topic}/{n}` | {DIFF[p['diff']]} | {p['title']} "
            f"| [#{p['lc']}](https://leetcode.com/problems/{p['slug']}/) | {p['pattern']} |"
        )
    rows.append(f"\nStart one with `python dsa.py start {topic}/1`.")
    return "\n".join(rows)


def solution(pid):
    """Markdown block with the reference solution of problem `pid` (topic/n)."""
    topic, n = pid.split("/")
    p = load(topic)[int(n) - 1]
    return (
        f"*Reference solution for **{p['title']}** (`{pid}`) - tested by `python dsa.py selftest`:*\n\n```python\n"
        + textwrap.dedent(p["solution"]).strip("\n")
        + "\n```"
    )


def index():
    """Markdown table of contents row for every topic."""
    rows = []
    for i, t in enumerate(TOPICS, 1):
        n = len(load(t))
        rows.append(f"| {i:02d} | [{t}]({i:02d}-{t}.md) | `{t}/1` ... `{t}/{n}` |")
    return "\n".join(rows)


def render(text, topic):
    """Fill the {{index}}, {{ladder}}, {{solution:...}} and {{trace:...}} placeholders in a notes template."""
    text = text.replace("{{index}}", index())
    text = text.replace("{{ladder}}", ladder(topic) if topic else "")
    text = re.sub(r"\{\{solution:([a-z_]+/\d+)\}\}", lambda m: solution(m.group(1)), text)

    def tr(m):
        """Replace one {{trace:name}} placeholder with its generated worked example."""
        if m.group(1) not in TRACES:
            sys.exit(f"unknown trace {m.group(1)}")
        return TRACES[m.group(1)]()

    return re.sub(r"\{\{trace:([a-z_0-9]+)\}\}", tr, text)


def main():
    """Write notes/<same name> for every file in _src/, plus notes/B3-coverage.md."""
    (ROOT / "notes").mkdir(exist_ok=True)
    count = 0
    for src in sorted((ROOT / "_src").glob("*.md")):
        m = re.match(r"(\d\d)-(.+)\.md", src.name)
        topic = m.group(2) if m and m.group(2) in TOPICS else None
        out = ROOT / "notes" / src.name
        text = render(src.read_text(encoding="utf-8"), topic)
        if topic:
            text = text.rstrip() + "\n" + anchors.render(topic)
        out.write_text(text, encoding="utf-8")
        count += 1
    (ROOT / "notes" / "B3-coverage.md").write_text(coverage.render(), encoding="utf-8")
    count += 1
    print(f"built {count} notes into notes/")


if __name__ == "__main__":
    main()
